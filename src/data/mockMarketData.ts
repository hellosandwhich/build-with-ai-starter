// Helper to generate realistic technical candle series for any symbol & timeframe
export function generateCandleData(basePrice: number, timeframe: Timeframe, count: number = 40): ChartCandle[] {
  const candles: ChartCandle[] = [];
  const now = Date.now();
  
  let stepMs = 60 * 1000; // 1 min for 1D
  if (timeframe === '5D') stepMs = 15 * 60 * 1000;
  if (timeframe === '1M') stepMs = 4 * 3600 * 1000;
  if (timeframe === '3M') stepMs = 24 * 3600 * 1000;
  if (timeframe === '1Y') stepMs = 3 * 24 * 3600 * 1000;
  if (timeframe === '5Y' || timeframe === 'ALL') stepMs = 14 * 24 * 3600 * 1000;

  let currentClose = basePrice * 0.94; // start slightly lower for trend
  const volatility = basePrice * 0.012;

  for (let i = 0; i < count; i++) {
    const timeTimestamp = now - (count - 1 - i) * stepMs;
    const dateObj = new Date(timeTimestamp);
    
    let timeLabel = dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    if (timeframe !== '1D' && timeframe !== '5D') {
      timeLabel = dateObj.toLocaleDateString([], { month: 'short', day: 'numeric' });
    }

    const open = currentClose;
    // slight positive drift to make it realistic
    const drift = (Math.random() - 0.47) * volatility;
    let close = open + drift;
    
    // ensure the last candle matches basePrice closely
    if (i === count - 1) {
      close = basePrice;
    }

    const high = Math.max(open, close) + Math.random() * volatility * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8;
    const volume = Math.floor(Math.random() * 500000 + 150000);

    candles.push({
      time: timeLabel,
      timestamp: timeTimestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });

    currentClose = close;
  }

  return candles;
}
